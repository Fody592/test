// Gzips dist-esp/index.html into a C header the ESP32 sketch serves from flash.
import { readFileSync, writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

const gz = gzipSync(readFileSync('dist-esp/index.html'), { level: 9 });
const bytes = Array.from(gz).map((b) => '0x' + b.toString(16).padStart(2, '0'));
const lines = [];
for (let i = 0; i < bytes.length; i += 16) lines.push('  ' + bytes.slice(i, i + 16).join(', '));
writeFileSync(
  'firmware/dispenser_wifi/index_html.h',
  `// AUTO-GENERATED by scripts/pack-esp.mjs - do not edit\n#pragma once\n#include <Arduino.h>\nconst size_t INDEX_HTML_GZ_LEN = ${gz.length};\nconst uint8_t INDEX_HTML_GZ[] PROGMEM = {\n${lines.join(',\n')}\n};\n`
);
console.log(`index_html.h written (${(gz.length / 1024).toFixed(1)} KB gzipped)`);
